import { createCipheriv, createDecipheriv, createHmac, hkdfSync, randomBytes, timingSafeEqual } from "node:crypto";

export class SessionStorageError extends Error {
  constructor() { super("SESSION_STORAGE_REJECTED"); this.name = "SessionStorageError"; }
}

export type SessionStorageRow = Record<string, unknown> & {
  id: string; userId: string; token: string; createdAt: Date; expiresAt: Date;
};

/** The independent file secret never reaches Prisma. HKDF separates encryption
 * and lookup purposes; neither persisted value is accepted as a bearer token. */
export function createSessionCodec(key: string) {
  if (typeof key !== "string" || !/^[a-f0-9]{64}$/.test(key)) throw new SessionStorageError();
  const material = Buffer.from(key, "hex");
  const encryption = Buffer.from(hkdfSync("sha256", material, "mq.session-storage.v1", "encryption", 32));
  const lookup = Buffer.from(hkdfSync("sha256", material, "mq.session-storage.v1", "lookup", 32));
  material.fill(0);
  const index = (token: string) => {
    if (typeof token !== "string" || !token.length || token.length > 1024) throw new SessionStorageError();
    return `hmac1:${createHmac("sha256", lookup).update(token, "utf8").digest("hex")}`;
  };
  const aad = (row: SessionStorageRow) => {
    if (typeof row.id !== "string" || !row.id.length || row.id.length > 256
      || typeof row.userId !== "string" || !row.userId.length || row.userId.length > 256
      || !/^hmac1:[a-f0-9]{64}$/.test(row.token)
      || !(row.createdAt instanceof Date) || !Number.isFinite(row.createdAt.getTime())
      || !(row.expiresAt instanceof Date) || !Number.isFinite(row.expiresAt.getTime())) throw new SessionStorageError();
    return Buffer.from(JSON.stringify(["mq.session-storage.v1", row.id, row.userId, row.token,
      row.createdAt.toISOString(), row.expiresAt.toISOString()]), "utf8");
  };
  return {
    index,
    seal<T extends SessionStorageRow>(row: T): T & { tokenCiphertext: string } {
      // This is the token format generated by the pinned Better Auth 1.7.12.
      if (typeof row.token !== "string" || !/^[A-Za-z0-9]{32}$/.test(row.token)) throw new SessionStorageError();
      const stored = { ...row, token: index(row.token) };
      const nonce = randomBytes(12);
      const cipher = createCipheriv("aes-256-gcm", encryption, nonce, { authTagLength: 16 });
      cipher.setAAD(aad(stored));
      const ciphertext = Buffer.concat([cipher.update(row.token, "utf8"), cipher.final()]);
      return { ...stored, tokenCiphertext: `v1:${nonce.toString("hex")}:${cipher.getAuthTag().toString("hex")}:${ciphertext.toString("hex")}` };
    },
    open<T extends SessionStorageRow>(row: T): SessionStorageRow & Omit<T, "tokenCiphertext"> {
      if (typeof row.tokenCiphertext !== "string"
        || !/^v1:[a-f0-9]{24}:[a-f0-9]{32}:[a-f0-9]{64}$/.test(row.tokenCiphertext)) throw new SessionStorageError();
      const [, nonce, tag, encrypted] = row.tokenCiphertext.split(":");
      let token: string;
      try {
        const decipher = createDecipheriv("aes-256-gcm", encryption, Buffer.from(nonce, "hex"), { authTagLength: 16 });
        decipher.setAAD(aad(row));
        decipher.setAuthTag(Buffer.from(tag, "hex"));
        token = Buffer.concat([decipher.update(Buffer.from(encrypted, "hex")), decipher.final()]).toString("utf8");
      } catch { throw new SessionStorageError(); }
      if (!/^[A-Za-z0-9]{32}$/.test(token)
        || !timingSafeEqual(Buffer.from(index(token)), Buffer.from(row.token))) throw new SessionStorageError();
      const result = { ...row, token };
      delete result.tokenCiphertext;
      return result;
    },
  };
}
